def eq(text):
    para=doc.add_paragraph()
    para.alignment=WD_ALIGN_PARAGRAPH.CENTER
    para.paragraph_format.space_before=Pt(3)
    para.paragraph_format.space_after=Pt(8)
    math=OxmlElement('m:oMath')
    def mr(value):
        run=OxmlElement('m:r'); txt=OxmlElement('m:t'); txt.text=value
        run.append(txt); return run
    last=0
    for match in re.finditer(r'([A-Za-z])_([A-Za-z]+(?:,[a-z])?)',text):
        if match.start()>last: math.append(mr(text[last:match.start()]))
        sub=OxmlElement('m:sSub');base=OxmlElement('m:e');base.append(mr(match.group(1)))
        tail=OxmlElement('m:sub');tail.append(mr(match.group(2)));sub.append(base);sub.append(tail);math.append(sub)
        last=match.end()
    if last<len(text): math.append(mr(text[last:]))
    para._p.append(math)
    return para

def table(headers, rows, widths):
    t=doc.add_table(rows=1, cols=len(headers))
    t.alignment=WD_TABLE_ALIGNMENT.CENTER
    t.autofit=False
    tblPr=t._tbl.tblPr
