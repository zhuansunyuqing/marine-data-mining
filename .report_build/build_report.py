    tblPr.append(borders)
    for i,width in enumerate(widths): t.columns[i].width=Cm(width)
    for i,v in enumerate(headers): t.rows[0].cells[i].text=v
    for vals in rows:
        for i,v in enumerate(vals):
            if i==0: cells=t.add_row().cells
            cells[i].text=str(v)
